    public PersonDbLayout PersonDb { get; set; } = new();
    public Hex GameDateRva { get; set; }
    public Hex PlayerVtableRva { get; set; }
    /// <summary>Other player classes: same person layout, player block shifted by Shift bytes.</summary>
    public PlayerClass[] ExtraPlayerClasses { get; set; } = [];
    public Hex HumanManagerVtableRva { get; set; }
    public RelationCodes RelationCodes { get; set; } = new();
    /// <summary>"built-in" (shipped, verified) or "doctor" (generated by Patch Doctor). Built-in wins for the same build.</summary>
    public string Origin { get; set; } = "built-in";
    public string? Generated { get; set; }
    /// <summary>Real players used by Patch Doctor to re-find the layout (full name, PA, height cm).</summary>
    public AnchorPlayer[] Anchors { get; set; } = [];
    /// <summary>Regex (case-insensitive) for women's clubs/competitions (men-only rule).</summary>
    public string WomensNamePattern { get; set; } = "";
    public Dictionary<string, string> SquadStatusNames { get; set; } = new();
    public Hex StaffVtableRva { get; set; }
    public Dictionary<string, string> JobNames { get; set; } = new();
    public PersonLayout Person { get; set; } = new();
    public NationLayout Nation { get; set; } = new();
    public ClubLayout Club { get; set; } = new();
    public ContractLayout Contract { get; set; } = new();
    public OfferLayout Offers { get; set; } = new();
    public TeamLayout Team { get; set; } = new();
    public PlayerLayout Player { get; set; } = new();
    public string[] PositionNames { get; set; } = [];
    public string[] AttributeNames { get; set; } = [];
    public string[] PersonalityNames { get; set; } = [];
}

